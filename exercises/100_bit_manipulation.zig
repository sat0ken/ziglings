//
// ビット操作は Zig でも非常に強力なツールです。
// コンピューター時代の夜明け以来、ビットを移動、設定、または
// 論理的に組み合わせるだけでタスクを解決する多くのアルゴリズムが
// 開発されてきました。
//
// Zig もその標準ライブラリで可能な関数にはビット操作を直接使用します。
// そして整数に基づいた計算では多くの場合可能です。
//
// 一見すると、メモリ領域内の「数値」だけが外部から変化するとき、
// これらのアルゴリズムが正確に何をしているのかを理解するのは
// 容易ではありません。しかし、数値はビット列の解釈を表しているに
// 過ぎないことを忘れてはいけません。
//
// 通常とは逆の場合、つまり数値をビット列で表現することを覚えています。
//
// 覚えておいてください：1 バイト = 8 ビット = 11111111 = 10進数で255 = 16進数でFF。
//
// Zig は変数内のビットを変更するために必要なすべての関数を提供します。
// ビット変更がオーバーフローを引き起こすかどうかで区別されます。
// 詳細は Zig ドキュメントの「演算子の表」セクションにあります。
//
// 変数のビットを変更する方法の例をいくつか示します：
//
//          const numOne: u8 = 15;        //   =  0000 1111
//          const numTwo: u8 = 245;       //   =  1111 0101
//
//          const res1 = numOne >> 4;     //   =  0000 0000 - 右シフト
//          const res2 = numOne << 4;     //   =  1111 0000 - 左シフト
//          const res3 = numOne & numTwo; //   =  0000 0101 - and
//          const res4 = numOne | numTwo; //   =  1111 1111 - or
//          const res5 = numOne ^ numTwo; //   =  1111 1010 - xor
//
//
// ビット操作に慣れるために、シンプルだがしばしば過小評価される関数から
// 始め、その後他の演習をゆるい順序で追加します。
//
// 以下のテキストにはウィキペディアからの抜粋が含まれています。
//
// スワップ
// コンピュータプログラミングにおいて、2つの変数のスワップとは
// 変数の値を互いに交換することを指します。通常、これはメモリ内の
// データで行われます。例えばプログラムでは、2つの変数が
// 次のように定義されるかもしれません（疑似コードで）：
//
//                        data_item x := 1
//                        data_item y := 0
//
//                        swap (x, y);
//
// swap() が実行された後、x は値 0 を含み、y は 1 を含みます；
// それらの値が交換されました。2つの変数をスワップする最もシンプルで
// おそらく最も広く使われる方法は、第3の一時変数を使うことです：
//
//                        define swap (x, y)
//                        temp := x
//                        x := y
//                        y := temp
//
// しかし整数の場合、ビット操作だけでスワップ関数を実現することもできます。
// そのためには変数を互いに xor でリンクすれば、結果は同じになります。

const std = @import("std");
const print = std.debug.print;

pub fn main() !void {

    // x と y の値として 1101 と 1011 を使います
    var x: u8 = 0b1101;
    var y: u8 = 0b1011;

    // xor を使って2つの変数の値をスワップします
    x ^= y;
    y ^= x;

    // ここに何を書けばよいですか？
    ???;

    print("x = {b}; y = {b}\n", .{ x, y });
}

// この変数スワップは、2つの値の xor から得られる値が
// その2つの値を両方含むという事実を利用しています。
// この性質は（今もなお）暗号化に使われることがあります。
// 値 XOR キー = 暗号文。=> 暗号文 XOR キー = 値。
// これは任意に入れ替えられるため、このようにして2つの変数を
// スワップできます。
//
// 暗号化には使わない方が良いですが、バブルソートのような
